"""
app/services/generation.py — Grounded answer generation using Google Gemini.

Responsibilities:
- Build the final grounded prompt from retrieved chunks + conversation history.
- Call the configured Gemini generation model.
- Support both standard (blocking) and streaming (SSE) generation.
- Parse and forward streaming output safely.
- Build source citations strictly from retrieved chunk metadata.
- Handle empty retrieval, model errors, rate limits, and timeouts.

Grounding guarantee: Citations are built from the retrieval metadata, not
from the model's own output. The model is never asked to produce citations.
"""

from __future__ import annotations

import asyncio
import time
from typing import Any, AsyncIterator, Dict, List, Optional

import google.generativeai as genai

from app.config import get_settings
from app.models.schemas import DebugInfo, SourceCitation
from app.rag.prompts import ANSWER_SYSTEM_PROMPT, build_answer_prompt
from app.utils.logging import get_logger

logger = get_logger(__name__)

_genai_configured = False


def _ensure_configured() -> None:
    global _genai_configured
    if _genai_configured:
        return
    settings = get_settings()
    if not settings.has_api_key():
        raise RuntimeError(
            "GOOGLE_API_KEY is not configured. Set it in your .env file."
        )
    genai.configure(api_key=settings.google_api_key)
    _genai_configured = True


def _build_sources(chunks: List[Dict[str, Any]]) -> List[SourceCitation]:
    """
    Build SourceCitation objects from retrieved chunk metadata.

    Citations are based strictly on the chunks that were retrieved and
    passed to the model — never generated by the model itself.
    """
    sources = []
    seen_chunk_ids = set()

    for chunk in chunks:
        cid = chunk.get("chunk_id", "")
        if cid in seen_chunk_ids:
            continue
        seen_chunk_ids.add(cid)

        meta = chunk.get("metadata", {})
        text = chunk.get("text", "")
        snippet = text[:300].strip()
        if len(text) > 300:
            snippet += "…"

        source = SourceCitation(
            chunk_id=cid,
            document_id=meta.get("document_id", ""),
            filename=meta.get("filename", "unknown"),
            page_number=meta.get("page_number"),
            chunk_index=meta.get("chunk_index", 0),
            text_snippet=snippet,
            vector_distance=chunk.get("vector_distance"),
            lexical_score=chunk.get("lexical_score"),
            rerank_score=chunk.get("rerank_score"),
        )
        sources.append(source)

    return sources


NO_CONTEXT_ANSWER = (
    "I cannot find the answer to this question in the uploaded documents. "
    "Please make sure you have uploaded the relevant documents and try again."
)


async def generate_answer(
    question: str,
    chunks: List[Dict[str, Any]],
    history: Optional[List[Dict[str, str]]] = None,
    retrieval_latency_ms: float = 0.0,
) -> Dict[str, Any]:
    """
    Generate a grounded answer (non-streaming).

    Args:
        question: The (possibly rewritten) question.
        chunks: Retrieved and reranked chunks.
        history: Conversation history for context.
        retrieval_latency_ms: Forwarded for debug info.

    Returns:
        Dict with keys: answer, sources, debug, model_used.
    """
    settings = get_settings()
    history = history or []

    # Handle empty retrieval gracefully — do not fabricate
    if not chunks:
        return {
            "answer": NO_CONTEXT_ANSWER,
            "sources": [],
            "debug": DebugInfo(
                retrieval_latency_ms=retrieval_latency_ms,
                num_candidates_retrieved=0,
                num_chunks_selected=0,
            ),
            "model_used": settings.gemini_model,
        }

    _ensure_configured()

    user_prompt = build_answer_prompt(
        question=question,
        context_chunks=chunks,
        conversation_history=history,
    )

    t_start = time.perf_counter()

    try:
        model = genai.GenerativeModel(
            model_name=settings.gemini_model,
            system_instruction=ANSWER_SYSTEM_PROMPT,
        )
        response = model.generate_content(user_prompt)
        answer_text = response.text or ""
    except Exception as exc:
        logger.error("Gemini generation failed: %s", exc)
        raise RuntimeError(f"Answer generation failed: {str(exc)[:300]}") from exc

    t_end = time.perf_counter()
    generation_latency_ms = (t_end - t_start) * 1000

    sources = _build_sources(chunks)

    debug = DebugInfo(
        num_candidates_retrieved=len(chunks),
        num_chunks_selected=len(chunks),
        retrieval_latency_ms=round(retrieval_latency_ms, 2),
        generation_latency_ms=round(generation_latency_ms, 2),
        total_latency_ms=round(retrieval_latency_ms + generation_latency_ms, 2),
        retrieved_chunks=[
            {
                "chunk_id": c.get("chunk_id"),
                "filename": c.get("metadata", {}).get("filename"),
                "page_number": c.get("metadata", {}).get("page_number"),
                "chunk_index": c.get("metadata", {}).get("chunk_index"),
                "vector_distance": c.get("vector_distance"),
                "lexical_score": c.get("lexical_score"),
                "rerank_score": c.get("rerank_score"),
                "text_preview": c.get("text", "")[:150],
            }
            for c in chunks
        ],
    )

    return {
        "answer": answer_text,
        "sources": sources,
        "debug": debug,
        "model_used": settings.gemini_model,
    }


async def stream_answer(
    question: str,
    chunks: List[Dict[str, Any]],
    history: Optional[List[Dict[str, str]]] = None,
    retrieval_latency_ms: float = 0.0,
) -> AsyncIterator[Dict[str, Any]]:
    """
    Stream a grounded answer using Gemini's streaming API.

    Yields dicts with 'event' and 'data' keys matching StreamEventType values:
      {"event": "start", "data": {...}}
      {"event": "token", "data": {"token": "..."}}
      {"event": "sources", "data": {"sources": [...]}}
      {"event": "done", "data": {...}}
      {"event": "error", "data": {"message": "..."}}

    Grounding: Sources are built from retrieved chunks, not model output.
    """
    settings = get_settings()
    history = history or []

    sources = _build_sources(chunks)

    # Emit start event
    yield {"event": "start", "data": {"session_id": "", "chunks_used": len(chunks)}}

    # Handle empty retrieval
    if not chunks:
        yield {"event": "token", "data": {"token": NO_CONTEXT_ANSWER}}
        yield {
            "event": "done",
            "data": {
                "total_latency_ms": round(retrieval_latency_ms, 2),
                "sources": [],
                "debug": {
                    "retrieval_latency_ms": retrieval_latency_ms,
                    "generation_latency_ms": 0,
                    "num_chunks_selected": 0,
                },
            },
        }
        return

    try:
        _ensure_configured()
    except RuntimeError as exc:
        yield {"event": "error", "data": {"message": str(exc)}}
        return

    user_prompt = build_answer_prompt(
        question=question,
        context_chunks=chunks,
        conversation_history=history,
    )

    t_start = time.perf_counter()

    try:
        model = genai.GenerativeModel(
            model_name=settings.gemini_model,
            system_instruction=ANSWER_SYSTEM_PROMPT,
        )
        response = model.generate_content(user_prompt, stream=True)

        for chunk_resp in response:
            token_text = chunk_resp.text if hasattr(chunk_resp, "text") else ""
            if token_text:
                yield {"event": "token", "data": {"token": token_text}}
                # Yield control to event loop so SSE can flush
                await asyncio.sleep(0)

    except Exception as exc:
        logger.error("Streaming generation failed: %s", exc)
        yield {"event": "error", "data": {"message": f"Generation error: {str(exc)[:200]}"}}
        return

    t_end = time.perf_counter()
    generation_latency_ms = (t_end - t_start) * 1000
    total_latency_ms = retrieval_latency_ms + generation_latency_ms

    # Emit sources
    yield {
        "event": "sources",
        "data": {"sources": [s.model_dump() for s in sources]},
    }

    # Emit done with debug metrics
    yield {
        "event": "done",
        "data": {
            "total_latency_ms": round(total_latency_ms, 2),
            "sources": [s.model_dump() for s in sources],
            "debug": {
                "retrieval_latency_ms": round(retrieval_latency_ms, 2),
                "generation_latency_ms": round(generation_latency_ms, 2),
                "total_latency_ms": round(total_latency_ms, 2),
                "num_chunks_selected": len(chunks),
                "model_used": settings.gemini_model,
                "retrieved_chunks": [
                    {
                        "chunk_id": c.get("chunk_id"),
                        "filename": c.get("metadata", {}).get("filename"),
                        "page_number": c.get("metadata", {}).get("page_number"),
                        "vector_distance": c.get("vector_distance"),
                        "lexical_score": c.get("lexical_score"),
                        "rerank_score": c.get("rerank_score"),
                        "text_preview": c.get("text", "")[:150],
                    }
                    for c in chunks
                ],
            },
        },
    }
